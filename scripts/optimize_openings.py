def optimize_article(filename):
    filepath = os.path.join(BLOG_DIR, filename)
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    if OLD_P not in content:
        print(f"  SKIP: Template text not found")
        return False
    
    new_p = OPTIMIZED.get(filename)
    if not new_p:
        print(f"  SKIP: No optimized version defined")
        return False
    
    content = content.replace(OLD_P, new_p, 1)
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    return True

